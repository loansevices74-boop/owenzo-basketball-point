import os
import requests
from crewai import Agent, Task, Crew, Process
from crewai_tools import ScrapeWebsiteTool
from langchain_openai import ChatOpenAI

# ==========================================
# OPEN-SOURCE LLM CONFIGURATION
# Uses OpenRouter's FREE tier (Mistral/Llama-3) for $0 inference cost.
# Alternatively, change base_url to "http://localhost:11434/v1" and model to "ollama/llama3" for 100% local.
# ==========================================
def get_open_source_llm():
    return ChatOpenAI(
        model="mistralai/mistral-7b-instruct:free", # 100% free open-source model via OpenRouter
        openai_api_base="https://openrouter.ai/api/v1",
        openai_api_key=os.getenv("OPENROUTER_API_KEY", "your_free_key_here"),
        temperature=0.3
    )

# ==========================================
# 1. DATA FETCHING (Your Existing Logic)
# ==========================================
def get_odds_data(sport_key: str, api_key: str):
    url = f"https://api.the-odds-api.com/v4/sports/{sport_key}/odds/?apiKey={api_key}&regions=us,eu&markets=h2h,totals"
    res = requests.get(url)
    return res.json() if res.status_code == 200 else []

def calculate_bounds(avg_home_score: float, avg_away_score: float):
    expected_total = (avg_home_score + avg_away_score)
    return {
        "expected_fulltime": round(expected_total, 1),
        "ft_over": round(expected_total + 5.5, 1),
        "ft_under": round(expected_total - 5.5, 1)
    }

# ==========================================
# 2. AUTONOMOUS AI AGENTS (crewAI + ScrapeGraphAI)
# ==========================================
def generate_premium_ai_report(country: str, league_name: str, sport_key: str, odds_api_key: str) -> str:
    """Generates a high-value, sellable digital betting report autonomously."""
    
    llm = get_open_source_llm()
    scrape_tool = ScrapeWebsiteTool()

    # Fetch top 3 matches to analyze
    matches = get_odds_data(sport_key, odds_api_key)[:3]
    if not matches:
        return "⚠️ No active matches found for this league right now. Try another league or check back later."

    # AGENT 1: The Sharp Researcher (Scrapes real-world context)
    researcher = Agent(
        role="Elite Sports Data Researcher",
        goal="Find critical real-world context (injuries, rest days, recent form) for basketball teams.",
        backstory="You use web search to find the hidden factors that bookmakers miss.",
        tools=[scrape_tool],
        llm=llm,
        verbose=False
    )

    # AGENT 2: The AI Handicapper (Analyzes odds + context)
    handicapper = Agent(
        role="Professional AI Sports Handicapper",
        goal="Generate a highly confident, data-backed betting prediction with clear reasoning.",
        backstory="You combine raw odds data with real-world research to find +EV (positive expected value) bets.",
        llm=llm,
        verbose=False
    )

    tasks = []
    for match in matches:
        home, away = match['home_team'], match['away_team']
        
        # Extract basic odds for the prompt
        bookmakers = match.get('bookmakers', [])
        odds_info = "No odds available"
        if bookmakers:
            markets = bookmakers[0].get('markets', [])
            if markets:
                outcomes = markets[0].get('outcomes', [])
                odds_info = ", ".join([f"{o['name']}: {o['price']}" for o in outcomes])

        tasks.append(Task(
            description=f"""
            Analyze this basketball match: {home} vs {away} in {league_name}.
            Current Odds: {odds_info}
            
            Step 1: Use your search tool to find recent news, injuries, or trends for '{home} basketball' and '{away} basketball'.
            Step 2: Based on the odds and your research, provide ONE specific, high-confidence betting pick (e.g., Moneyline, Spread, or Total).
            Step 3: Write 2-3 sentences of 'Sharp Reasoning' explaining why this is a valuable bet.
            """,
            expected_output="A structured betting pick with team names, the specific bet, and sharp reasoning.",
            agent=handicapper
        ))

    # Execute the Crew
    crew = Crew(agents=[researcher, handicapper], tasks=tasks, process=Process.sequential)
    result = crew.kickoff()

    # Format as a Premium Digital Product
    premium_report = f"""
# 🏀 **PREMIUM AI BETTING INTELLIGENCE REPORT** 🏀
**League:** {country} - {league_name}  
**Generated By:** Owenzo Autonomous AI Handicapper  
**Date:** Today  

---
### 📊 **TOP AI-GENERATED VALUE PICKS**

{result.raw}

---
### 🔒 **UNLOCK THE FULL 10-LEG ACCUMULATOR SLIP**
The free report above contains 3 AI-analyzed picks. 
Our **Premium Daily Slip** includes:
✅ 10-Leg High-Confidence Accumulator  
✅ Live Line-Movement Alerts  
✅ Exact Stake Sizing (Kelly Criterion)  

👉 **[GET LIFETIME ACCESS FOR $19.99](https://buy.stripe.com/YOUR_STRIPE_LINK_HERE)** 👈
"""
    return premium_report